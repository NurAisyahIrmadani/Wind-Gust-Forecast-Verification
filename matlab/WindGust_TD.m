%% ============================================================
% 4. SETTINGS
% ============================================================

forecast_cols = {'F_0','F_6','F_12','F_18','F_24'};

forecast_labels = { ...
    '0 h', ...
    '6 h', ...
    '12 h', ...
    '18 h', ...
    '24 h'};

markers = {'o','d','s','^','v'};

colors = lines(5);

unique_times = unique(data.Time,'stable');


%% ============================================================
% 5. CREATE FIGURE
% ============================================================

figure( ...
    'Position',[100 50 1400 900], ...
    'Color','w');


%% ============================================================
% 6. LOOP THROUGH EACH LOCAL TIME
% ============================================================

for t = 1:length(unique_times)

    current_time = unique_times(t);

    % Select current local time
    time_idx = data.Time == current_time;

    sub_data = data(time_idx,:);

    % ERA5 observation
    ref_signal = sub_data.Observation;

    nForecast = length(forecast_cols);


    %% --------------------------------------------------------
    % Calculate Taylor statistics
    % ---------------------------------------------------------

    SDEV  = zeros(nForecast+1,1);
    CRMSD = zeros(nForecast+1,1);
    CORR  = zeros(nForecast+1,1);


    % ---------------------------------------------------------
    % Observation / reference
    % ---------------------------------------------------------

    obs_stats = taylor_statistics( ...
        ref_signal, ...
        ref_signal);

    SDEV(1)  = obs_stats.sdev(1);
    CRMSD(1) = 0;
    CORR(1) = 1;


    % ---------------------------------------------------------
    % Forecast statistics
    % ---------------------------------------------------------

    for f = 1:nForecast

        forecast_signal = sub_data.(forecast_cols{f});

        % Remove missing values
        valid = ...
            isfinite(ref_signal) & ...
            isfinite(forecast_signal);

        ref_valid = ref_signal(valid);
        forecast_valid = forecast_signal(valid);

        % Taylor statistics
        stats = taylor_statistics( ...
            forecast_valid, ...
            ref_valid);

        SDEV(f+1) = stats.sdev(2);
        CRMSD(f+1) = stats.crmsd(2);
        CORR(f+1) = stats.ccoef(2);

    end


    %% --------------------------------------------------------
    % Create subplot
    % ---------------------------------------------------------

    subplot(2,2,t);


    %% --------------------------------------------------------
    % Taylor Diagram
    %
    % IMPORTANT:
    % markerLabel is intentionally NOT used.
    % It caused the previous error.
    % ---------------------------------------------------------

    [hp,ht,axl] = taylor_diagram( ...
        SDEV, ...
        CRMSD, ...
        CORR, ...
        'markerLegend','off', ...
        'markerSize',9, ...
        'markerSymbol','o', ...
        'styleOBS','-', ...
        'markerObs','o', ...
        'titleOBS','ERA5', ...
        'checkStats','on');


    %% --------------------------------------------------------
    % Modify forecast markers
    % ---------------------------------------------------------

    % Find plotted marker objects
    marker_objects = findobj(gca,'Type','line');

    % Counter for forecast markers
    marker_count = 0;

    for k = 1:length(marker_objects)

        % Get marker
        current_marker = get(marker_objects(k),'Marker');

        % Ignore objects without markers
        if strcmp(current_marker,'none')
            continue
        end

        marker_count = marker_count + 1;

        % Only modify the five forecast markers
        if marker_count <= nForecast

            set(marker_objects(k), ...
                'Marker',markers{marker_count}, ...
                'MarkerSize',9, ...
                'MarkerFaceColor',colors(marker_count,:), ...
                'MarkerEdgeColor','k');

        end

    end


    %% --------------------------------------------------------
    % Panel title
    % ---------------------------------------------------------

    title( ...
        sprintf('Valid Time: %s WITA',char(current_time)), ...
        'FontWeight','bold', ...
        'FontSize',13);

end


